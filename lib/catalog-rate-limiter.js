export const ANILIST_RATE_LIMIT = Object.freeze({
  refillTokens: 1,
  refillInterval: "3 s",
  refillIntervalMs: 3_000,
  maxBurstTokens: 5,
  requestsPerMinute: 20,
});
const REFILL_TOKENS = ANILIST_RATE_LIMIT.refillTokens;
const REFILL_INTERVAL = ANILIST_RATE_LIMIT.refillInterval;
const REFILL_INTERVAL_MS = ANILIST_RATE_LIMIT.refillIntervalMs;
const MAX_BURST_TOKENS = ANILIST_RATE_LIMIT.maxBurstTokens;
const MAX_PERMIT_WAIT_MS = 12_000;
const REDIS_TIMEOUT_MS = 800;
const RATE_LIMIT_PREFIX = "anibloom:anilist:upstream:v1";

function getRateLimitPrefix() {
  const environment = process.env.VERCEL_ENV || (process.env.NODE_ENV === "production" ? "production" : "development");
  return `${RATE_LIMIT_PREFIX}:${environment}`;
}

let sharedLimiterPromise = null;
let injectedLimiter = null;
let warnedAboutFallback = false;
let localBucket = {
  tokens: MAX_BURST_TOKENS,
  updatedAt: Date.now(),
};

export function getAniListRedisCredentials() {
  // Prefer the names generated by the Vercel Upstash Marketplace integration.
  const marketplaceUrl = process.env.UPSTASH_REDIS_REST_URL;
  const marketplaceToken = process.env.UPSTASH_REDIS_REST_TOKEN;
  if (marketplaceUrl && marketplaceToken) {
    return { url: marketplaceUrl, token: marketplaceToken };
  }

  // Retain compatibility with the original KV-prefixed configuration.
  const kvUrl = process.env.UPSTASH_REDIS_REST_KV_REST_API_URL;
  const kvToken = process.env.UPSTASH_REDIS_REST_KV_REST_API_TOKEN;
  if (kvUrl && kvToken) {
    return { url: kvUrl, token: kvToken };
  }

  return null;
}

async function getSharedLimiter() {
  if (injectedLimiter) return injectedLimiter;
  if (!getAniListRedisCredentials()) return null;

  if (!sharedLimiterPromise) {
    sharedLimiterPromise = Promise.all([
      import("@upstash/redis"),
      import("@upstash/ratelimit"),
    ]).then(([{ Redis }, { Ratelimit }]) => {
      const credentials = getAniListRedisCredentials();
      if (!credentials) return null;
      const redis = new Redis(credentials);
      return new Ratelimit({
        redis,
        limiter: Ratelimit.tokenBucket(REFILL_TOKENS, REFILL_INTERVAL, MAX_BURST_TOKENS),
        prefix: getRateLimitPrefix(),
        analytics: false,
        enableTelemetry: false,
        timeout: REDIS_TIMEOUT_MS,
        ephemeralCache: new Map(),
      });
    }).catch(() => null);
  }
  return sharedLimiterPromise;
}

function takeLocalFallbackToken(now = Date.now()) {
  const elapsed = Math.max(0, now - localBucket.updatedAt);
  const refillPerMs = REFILL_TOKENS / REFILL_INTERVAL_MS;
  localBucket.tokens = Math.min(MAX_BURST_TOKENS, localBucket.tokens + elapsed * refillPerMs);
  localBucket.updatedAt = now;

  if (localBucket.tokens >= 1) {
    localBucket.tokens -= 1;
    return { allowed: true, source: "instance-fallback", retryAfterMs: 0 };
  }

  const retryAfterMs = Math.ceil((1 - localBucket.tokens) / refillPerMs);
  return { allowed: false, source: "instance-fallback", retryAfterMs };
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function tryAcquireAniListRequestPermit() {
  if (injectedLimiter) {
    const result = await injectedLimiter();
    const allowed = Boolean(result?.success ?? result?.allowed);
    return {
      allowed,
      source: "injected",
      retryAfterMs: allowed ? 0 : Math.max(1_000, Number(result?.reset || 0) - Date.now()),
    };
  }

  const limiter = await getSharedLimiter();
  if (limiter) {
    try {
      const result = await limiter.limit("global");
      if (result.success) return { allowed: true, source: "upstash", retryAfterMs: 0 };
      return {
        allowed: false,
        source: "upstash",
        retryAfterMs: Math.max(1_000, Number(result.reset || 0) - Date.now()),
      };
    } catch (error) {
      if (!warnedAboutFallback) {
        warnedAboutFallback = true;
        console.warn("[anilist] distributed rate limiter unavailable; using instance-local fallback", {
          kind: error?.name || "error",
        });
      }
    }
  } else if (!warnedAboutFallback) {
    warnedAboutFallback = true;
    console.warn("[anilist] distributed rate limiter is not configured; using instance-local fallback");
  }

  return takeLocalFallbackToken();
}

export async function acquireAniListRequestPermit({ maxWaitMs = MAX_PERMIT_WAIT_MS, wait = sleep } = {}) {
  const startedAt = Date.now();
  const maxWait = Math.max(0, Number(maxWaitMs) || 0);

  while (true) {
    const permit = await tryAcquireAniListRequestPermit();
    if (permit.allowed) {
      return { ...permit, waitedMs: Math.max(0, Date.now() - startedAt) };
    }

    const waitedMs = Math.max(0, Date.now() - startedAt);
    const remainingMs = Math.max(0, maxWait - waitedMs);
    const retryAfterMs = Math.max(1, Number(permit.retryAfterMs) || 1_000);
    if (retryAfterMs > remainingMs) {
      return { ...permit, retryAfterMs, waitedMs };
    }

    await wait(retryAfterMs);
  }
}

export function setAniListRateLimiterForTests(limiter) {
  injectedLimiter = limiter || null;
  sharedLimiterPromise = null;
  warnedAboutFallback = false;
  resetAniListLocalFallbackForTests();
}

export function resetAniListLocalFallbackForTests(now = Date.now()) {
  localBucket = { tokens: MAX_BURST_TOKENS, updatedAt: now };
  warnedAboutFallback = false;
}
