import assert from "node:assert/strict";
import test from "node:test";
import { getAniListRedisCredentials } from "../lib/catalog-rate-limiter.js";

const ENV_KEYS = [
  "UPSTASH_REDIS_REST_URL",
  "UPSTASH_REDIS_REST_TOKEN",
  "UPSTASH_REDIS_REST_KV_REST_API_URL",
  "UPSTASH_REDIS_REST_KV_REST_API_TOKEN",
];

function withRedisEnvironment(values, run) {
  const previous = Object.fromEntries(ENV_KEYS.map((key) => [key, process.env[key]]));
  for (const key of ENV_KEYS) {
    if (Object.hasOwn(values, key)) process.env[key] = values[key];
    else delete process.env[key];
  }

  try {
    return run();
  } finally {
    for (const key of ENV_KEYS) {
      if (previous[key] === undefined) delete process.env[key];
      else process.env[key] = previous[key];
    }
  }
}

test("reads the REST URL and token names generated by the Upstash Marketplace integration", () => {
  withRedisEnvironment({
    UPSTASH_REDIS_REST_URL: "https://redis.example.test",
    UPSTASH_REDIS_REST_TOKEN: "marketplace-test-token",
  }, () => {
    assert.deepEqual(getAniListRedisCredentials(), {
      url: "https://redis.example.test",
      token: "marketplace-test-token",
    });
  });
});

test("retains support for the original KV-prefixed Upstash environment variables", () => {
  withRedisEnvironment({
    UPSTASH_REDIS_REST_KV_REST_API_URL: "https://legacy-redis.example.test",
    UPSTASH_REDIS_REST_KV_REST_API_TOKEN: "legacy-test-token",
  }, () => {
    assert.deepEqual(getAniListRedisCredentials(), {
      url: "https://legacy-redis.example.test",
      token: "legacy-test-token",
    });
  });
});

test("prefers a complete Marketplace credential pair when both naming schemes exist", () => {
  withRedisEnvironment({
    UPSTASH_REDIS_REST_URL: "https://marketplace.example.test",
    UPSTASH_REDIS_REST_TOKEN: "marketplace-token",
    UPSTASH_REDIS_REST_KV_REST_API_URL: "https://legacy.example.test",
    UPSTASH_REDIS_REST_KV_REST_API_TOKEN: "legacy-token",
  }, () => {
    assert.deepEqual(getAniListRedisCredentials(), {
      url: "https://marketplace.example.test",
      token: "marketplace-token",
    });
  });
});

test("does not combine incomplete credentials from different naming schemes", () => {
  withRedisEnvironment({
    UPSTASH_REDIS_REST_URL: "https://marketplace.example.test",
    UPSTASH_REDIS_REST_KV_REST_API_TOKEN: "legacy-token",
  }, () => {
    assert.equal(getAniListRedisCredentials(), null);
  });
});

test("distributed AniList token bucket refills smoothly at the configured 20 requests per minute", async () => {
  const { ANILIST_RATE_LIMIT } = await import("../lib/catalog-rate-limiter.js");
  assert.deepEqual(ANILIST_RATE_LIMIT, {
    refillTokens: 1,
    refillInterval: "3 s",
    refillIntervalMs: 3_000,
    maxBurstTokens: 5,
    requestsPerMinute: 20,
  });
});
